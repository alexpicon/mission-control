// Core domain types for Mission Control.

export type Status = "Moving" | "Blocked" | "Done" | "Idea";
export const STATUSES: Status[] = ["Moving", "Blocked", "Done", "Idea"];

// How a project's progress is displayed. "evidence" is derived live from its
// mvp_items and takes over automatically once an MVP file has been scanned
// and approved at least once; "manual" is the fallback slider.
export type ProgressMode = "manual" | "evidence";

export interface Project {
  id: number;
  name: string;
  goal: string;
  status: Status;
  progress: number; // 0..100 — manual fallback only, not the main workflow
  blocker: string;
  next_step: string;
  is_focus: number; // 0 | 1
  path: string; // local folder path; connects the app to a real codebase
  claude_connected: number; // 0 | 1
  mvp_file_path: string; // relative or absolute path to the connected MVP/spec file
  mvp_file_hash: string; // content hash as of the last time the file was scanned
  mvp_file_mtime: string; // file mtime (epoch seconds, as string) as of last scan
  progress_mode: ProgressMode;
  created_at: string; // SQLite UTC "YYYY-MM-DD HH:MM:SS"
  updated_at: string;
}

export type UpdateKind = "progress" | "decision" | "blocker" | "note";
export const UPDATE_KINDS: UpdateKind[] = ["progress", "decision", "blocker", "note"];

export interface Update {
  id: number;
  project_id: number;
  kind: UpdateKind;
  body: string;
  source: "manual" | "claude-code"; // claude-code reserved for future hook
  status: "accepted" | "proposed" | "rejected"; // future approve/edit/reject
  created_at: string;
}

// Fields the user can edit through the project form.
export interface ProjectInput {
  name: string;
  goal: string;
  status: Status;
  progress: number;
  blocker: string;
  next_step: string;
  path: string;
  mvp_file_path: string;
}

// A proposed (not yet applied) update generated from a Claude Code session.
export interface ProposedUpdate {
  id: number;
  project_id: number;
  session_id: string;
  summary: string;
  files_changed: string; // newline-separated
  status: "pending" | "approved" | "rejected";
  created_at: string;
}

// A raw Claude Code hook event, as persisted for summarization.
export interface CcEvent {
  id: number;
  session_id: string;
  project_id: number | null;
  cwd: string;
  event_name: string;
  tool_name: string;
  payload: string; // raw hook JSON
  created_at: string;
}

// --- Evidence-based progress -----------------------------------------------

export type MvpPriority = "must_have" | "should_have" | "nice_to_have";
export const MVP_PRIORITIES: MvpPriority[] = ["must_have", "should_have", "nice_to_have"];

export type MvpItemStatus = "not_started" | "in_progress" | "blocked" | "done" | "cut";
export const MVP_ITEM_STATUSES: MvpItemStatus[] = [
  "not_started",
  "in_progress",
  "blocked",
  "done",
  "cut",
];

export type Confidence = "low" | "medium" | "high";

// Where an MVP item's text came from — never fabricated, always traceable.
export type MvpItemSource = "mvp_file" | "ai_extracted" | "manual";

export interface MvpItem {
  id: number;
  project_id: number;
  title: string;
  description: string;
  priority: MvpPriority;
  status: MvpItemStatus;
  evidence: string; // free text — file names / reasoning behind the current status
  confidence: Confidence;
  source: MvpItemSource;
  created_at: string;
  updated_at: string;
}

// A single item as freshly parsed/extracted from an MVP file, before it is
// diffed against what's already in the database.
export interface ParsedMvpItem {
  title: string;
  description: string;
  priority: MvpPriority;
  done: boolean; // local checkbox parser only knows done vs not — AI extraction may say more
}

// A proposed change to project scope, generated by diffing a re-parsed MVP
// file against the current mvp_items. Requires explicit approve/edit/reject —
// mvp_items are never changed until this is approved.
export interface ProposedScopeUpdate {
  id: number;
  project_id: number;
  file_hash: string;
  file_mtime: string;
  diff_json: string; // serialized MvpScopeDiff
  old_progress: number;
  new_progress: number;
  status: "pending" | "approved" | "rejected";
  created_at: string;
}

export interface MvpScopeDiff {
  added: ParsedMvpItem[];
  removed: { title: string; priority: MvpPriority }[]; // matched against current items by title
  changed: {
    title: string;
    before: { priority: MvpPriority };
    after: { priority: MvpPriority };
  }[];
  usedAi: boolean;
}

// A proposed status change for one MVP item, generated from Claude Code
// session evidence or a folder scan. Never applied until approved.
export interface ProposedItemUpdate {
  id: number;
  project_id: number;
  mvp_item_id: number;
  suggested_status: MvpItemStatus;
  evidence: string; // newline-separated file list / reasoning
  confidence: Confidence;
  source: "claude-code" | "folder-scan";
  session_id: string;
  status: "pending" | "approved" | "rejected";
  created_at: string;
}

export type ScanCategory = "code" | "docs" | "tests" | "config" | "dependencies" | "mvp_scope";

// A single file as reported by the Rust folder scanner. Sensitive/ignored/
// binary files are excluded before this ever reaches the frontend.
export interface ScannedFile {
  path: string; // relative to the project folder
  category: ScanCategory;
  hash: string; // empty for large files (mtime/size used for change detection instead)
  mtime: string;
  size: number;
}

// The last-seen state of a project's folder, stored so scans can diff
// against "what changed" instead of re-reading everything every time.
export interface FolderSnapshotEntry {
  project_id: number;
  file_path: string;
  category: ScanCategory;
  hash: string;
  mtime: string;
  size: number;
}
